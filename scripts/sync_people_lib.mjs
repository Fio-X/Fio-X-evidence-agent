// Copy the people library (lib.js, skins/*.js, its JSON data) into runtime/illus_hero/scene/people_lib/
// so the scene node imports it with no file read at run time: every *.json becomes `<name>.data.mjs`
// (`export default {...};`) and lib.js's loader (fs / fetch / import.meta.url / top-level await) is
// replaced by static imports of those modules. Deterministic and re-runnable; never hand-edit the copy.
//
//   node scripts/sync_people_lib.mjs [<source dir>]
//
// The source dir is the argument or $PEOPLE_LIB_SRC; with neither the script stops (it never guesses a folder).
// Prints the sha256 of every source file it copied.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcArg = process.argv[2] || process.env.PEOPLE_LIB_SRC;
if (!srcArg) { console.error('sync_people_lib: give the people library folder as the argument or in PEOPLE_LIB_SRC'); process.exit(2); }
const src = resolve(srcArg);
const out = join(repo, 'runtime/illus_hero/scene/people_lib');
const DATA = ['poses', 'bodies', 'hair', 'outfits', 'scenes'];
const HEADER = '// GENERATED by scripts/sync_people_lib.mjs from the people library; do not edit by hand.\n';

if (!existsSync(join(src, 'lib.js'))) { console.error(`sync_people_lib: no lib.js in ${src}`); process.exit(2); }
const sha = (b) => createHash('sha256').update(b).digest('hex');
const hashes = [];
const read = (rel) => { const b = readFileSync(join(src, rel)); hashes.push([rel, sha(b)]); return b.toString('utf8'); };

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'skins'), { recursive: true });

// data: JSON -> ES module (keys kept in source order; JSON.stringify of the parsed value is stable)
for (const name of DATA) {
  const value = JSON.parse(read(`${name}.json`));
  writeFileSync(join(out, `${name}.data.mjs`), `${HEADER}export default ${JSON.stringify(value)};\n`);
}

// lib.js: the loader block (from `const isNode` to the closing `};` of `const DATA = {`) becomes static imports
let lib = read('lib.js');
const start = lib.indexOf('const isNode');
const dataAt = lib.indexOf('const DATA = {', start);
const end = dataAt < 0 ? -1 : lib.indexOf('\n};', dataAt);
if (start < 0 || dataAt < 0 || end < 0) { console.error('sync_people_lib: lib.js loader block not found (the library changed its loader; update this script)'); process.exit(3); }
const imports = DATA.map((n) => `import ${n}Data from './${n}.data.mjs';`).join('\n');
const block = `${imports}\nconst DATA = { ${DATA.map((n) => `${n}: ${n}Data`).join(', ')} };`;
lib = HEADER + lib.slice(0, start) + block + lib.slice(end + 3);
const LIB = lib.replace(/from '\.\/skins\/([a-z]+)\.js'/g, "from './skins/$1.mjs'");

// skins: copied as .mjs (so node treats them as ES modules without a package.json); sibling imports renamed
for (const f of readdirSync(join(src, 'skins')).filter((f) => f.endsWith('.js')).sort()) {
  const body = read(`skins/${f}`).replace(/from '\.\/([a-z_]+)\.js'/g, "from './$1.mjs'").replace(/from '\.\.\/lib\.js'/g, "from '../lib.mjs'");
  writeFileSync(join(out, 'skins', f.replace(/\.js$/, '.mjs')), HEADER + body);
}

writeFileSync(join(out, 'lib.mjs'), LIB);
// the copy must read nothing at run time
const bad = [];
const walk = (d) => { for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) { const p = join(d, e.name); if (e.isDirectory()) walk(p); else { const t = readFileSync(p, 'utf8'); for (const [re, why] of [[/\bnode:fs\b|\brequire\(|\bfetch\(/, 'fs/fetch'], [/import\.meta/, 'import.meta'], [/^\s*(?:const|let|var)?[^\n]*\bawait\b/m, 'await'], [/\bimport\(/, 'dynamic import']]) if (re.test(t)) bad.push(`${p}: ${why}`); } } };
walk(out);
if (bad.length) { console.error('sync_people_lib: the copy still reads files:\n' + bad.join('\n')); process.exit(4); }

// lib.mjs carries the source hashes in its header so a stale copy is visible without another file
writeFileSync(join(out, 'lib.mjs'), LIB.replace(HEADER, HEADER + hashes.map(([f, h]) => `// sha256 ${h}  ${f}\n`).join('')));
for (const [f, h] of hashes) console.log(`${h}  ${f}`);
console.log(`sync_people_lib: ${hashes.length} files -> ${out}`);
