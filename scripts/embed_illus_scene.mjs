// Embed every file under runtime/illus_hero/scene/ (the scene renderer's node and its people library copy) and register it, the way the
// other opening-picture files are: src/runtime.rs gets one create_dir_all per folder and one include_str! row per file between its
// BEGIN/END illus_hero/scene lines (literal runtime_dir.join names, so scripts/test_runtime_materialize_rules.mjs and test_group_kinds.mjs
// see them), runtime/pi/groups.json one run_record row per folder and one materialized_runtime row per folder and file (exact names).
// Deterministic and re-runnable: re-run after scripts/sync_people_lib.mjs or any change of the folder's file list (test_group_kinds.mjs
// fails while a file under scene/ is not embedded). Writes only those two files.
//
//   node scripts/embed_illus_scene.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCENE = 'illus_hero/scene';
const dirs = [SCENE], files = [];
const walk = (rel) => {
  for (const e of readdirSync(join(repo, 'runtime', rel), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const r = `${rel}/${e.name}`;
    if (e.isDirectory()) { dirs.push(r); walk(r); } else if (e.isFile()) files.push(r);
  }
};
walk(SCENE);
if (!files.includes(`${SCENE}/scene.mjs`)) { console.error('embed_illus_scene: no runtime/illus_hero/scene/scene.mjs'); process.exit(2); }

// src/runtime.rs, in rustfmt's own layout
const BEGIN = '    // BEGIN illus_hero/scene: generated by scripts/embed_illus_scene.mjs (the scene renderer run_hero.py starts), do not edit by hand\n';
const END = '    // END illus_hero/scene\n';
const block = BEGIN
  + '    for dir in [\n' + dirs.map((d) => `        runtime_dir.join("${d}"),\n`).join('') + '    ] {\n'
  + '        crate::group_guard::create_dir_all(artifact_dir, &dir).with_context(|| {\n'
  + '            format!(\n                "failed to create the scene runtime directory: {}",\n                dir.display()\n            )\n        })?;\n    }\n'
  + '    for (path, text) in [\n'
  + files.map((f) => `        (\n            runtime_dir.join("${f}"),\n            include_str!("../runtime/${f}"),\n        ),\n`).join('')
  + '    ] {\n        write_if_changed(artifact_dir, &path, text)?;\n    }\n'
  + END;
const rsPath = join(repo, 'src/runtime.rs');
let rs = readFileSync(rsPath, 'utf8');
const a = rs.indexOf(BEGIN), b = rs.indexOf(END);
if (a >= 0 && b > a) rs = rs.slice(0, a) + block + rs.slice(b + END.length);
else {
  // first run: after the loop that writes the people drawing's files
  const anchor = '            include_str!("../runtime/illus_hero/people/people.json"),\n        ),\n    ] {\n        write_if_changed(artifact_dir, &path, text)?;\n    }\n';
  const at = rs.indexOf(anchor);
  if (at < 0) { console.error('embed_illus_scene: the people drawing rows of src/runtime.rs moved; place the BEGIN/END lines by hand once'); process.exit(3); }
  rs = rs.slice(0, at + anchor.length) + block + rs.slice(at + anchor.length);
}
writeFileSync(rsPath, rs);

// runtime/pi/groups.json: the scene rows right after the people drawing's own
const gPath = join(repo, 'runtime/pi/groups.json');
const groups = JSON.parse(readFileSync(gPath, 'utf8'));
const rules = groups.artifact_kinds.rules;
const ours = (r) => typeof r.exact === 'string' && (r.exact === `runtime/${SCENE}` || r.exact.startsWith(`runtime/${SCENE}/`));
const kept = rules.filter((r) => !ours(r));
const NOTE = 'Written only by runtime.rs materialize_extension (a build copy of the same name under runtime/illus_hero/scene/, listed by scripts/embed_illus_scene.mjs): the opening illustration child\'s scene renderer, its node or its people library copy. Listed as a fixed name, not a folder rule, so the rest of runtime/ stays the agent group\'s.';
const records = dirs.map((d) => ({ kind: 'run_record', exact: `runtime/${d}/`, note: 'Created by runtime.rs materialize_extension (group_guard create_dir_all) to hold the scene renderer the opening illustration child starts (scripts/embed_illus_scene.mjs): a folder of the run bundle, no content of its own.' }));
const written = [...dirs.map((d) => ({ kind: 'materialized_runtime', exact: `runtime/${d}`, note: 'The folder runtime.rs materialize_extension creates for the opening illustration child\'s scene renderer (each file in it has its own exact row; scripts/embed_illus_scene.mjs). Listed as a fixed name, not a folder rule.' })),
  ...files.map((f) => ({ kind: 'materialized_runtime', exact: `runtime/${f}`, note: NOTE }))];
const after = (exact, rows) => {
  const i = kept.findIndex((r) => r.exact === exact);
  if (i < 0) { console.error(`embed_illus_scene: no groups.json row ${exact}`); process.exit(4); }
  kept.splice(i + 1, 0, ...rows);
};
after('runtime/illus_hero/people/', records);
after('runtime/illus_hero/people/people.json', written);
groups.artifact_kinds.rules = kept;
writeFileSync(gPath, JSON.stringify(groups, null, 1) + '\n');
console.log(`embed_illus_scene: ${dirs.length} folders, ${files.length} files`);
