#!/usr/bin/env node
// geometric-cover/1 - a bundled, data-free software illustration adapter.
//
// It draws a decorative page cover (no text, no numbers, no map, no chart
// grammar) behind the existing provenance-checked illustration path:
// newsroom_illustration_plan -> lint -> generate -> critic. generate runs this
// file shell-free (NEWSROOM_ILLUSTRATION_ADAPTER = the node binary,
// NEWSROOM_ILLUSTRATION_ADAPTER_ARGS_JSON = ["<this file>"]), writes one
// request JSON on stdin and parses one response JSON from stdout. Every gate
// (normalizeIllustrationAdapterResponse, critiqueRichIllustration, assertSafeSvg,
// the page lint and render QA) is unchanged and still applies to what this
// prints. With the env var unset nothing here ever runs.
//
// What it reads from the request, and nothing else:
//   protocol, request_hash (the only seed), policy.origin_policy and
//   spec.origin_policy, spec.factual_elements and evidence.factual_elements
//   (only to refuse a non-empty list), spec.title and spec.alt (only to refuse
//   digits and percent signs, because annotateSvg copies them into <title> and
//   <desc>), and the motif=<family> token in spec.constraints.
// It never reads the subject, intent, style text, claim ids, evidence refs or
// source note, and the drawing functions receive only {family, seed, viewport}.
// Element counts come from the layout tables below, never from the request.
//
// Refusals print one line on stderr, print nothing on stdout, and exit with a
// distinct code. The model only ever sees "Process exited with code N" (the
// pipeline does not surface adapter stderr), so the code is the contract:
//   2  origin_policy is not software_only
//   3  factual_elements is not empty (a decorative generator never depicts facts)
//   4  title or alt contains a digit or a percent sign
//   5  motif= token missing, repeated, or not in the closed family set
//   6  malformed request (not JSON, wrong protocol, no request_hash)
//   7  house palette unavailable (viz.mjs not found beside the adapter)
//
// Design rules that keep a cover from reading as data:
//   - one shape size, stroke width and spacing per family and viewport;
//   - two neutral greys plus the accent, assigned by seeded chance and never
//     by position, so tones cannot form a ramp;
//   - the accent is a small fixed count of small pieces, never a field;
//   - no text, tspan, image, gradient, filter, clip, axes, ticks, scales,
//     legends, map shapes or flags; no background rect (the page is the paper);
//   - no trigonometry: every coordinate is plain IEEE arithmetic rounded to one
//     decimal, so the same request gives the same bytes on every platform.

import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ADAPTER_ID = 'geometric-cover/1';
const PROTOCOL = 'agentic-data-newsroom.rich-illustration.v1';
const FAMILIES = Object.freeze(['arcs', 'concentric', 'bands']);
const EXIT = Object.freeze({ INTERNAL: 1, POLICY: 2, FACTUAL: 3, DIGITS: 4, MOTIF: 5, MALFORMED: 6, PALETTE: 7 });

const DISCLOSURE = '软件生成的装饰图，不含数据';
const LICENSE = 'MIT (generated by agentic-data-newsroom; no third-party material)';
const DIGIT_OR_PERCENT = /[\p{N}%％﹪٪‰‱]/u;
const HEX_COLOR = /^#[0-9a-fA-F]{6}$/;

const VIEWPORTS = Object.freeze({
  desktop: Object.freeze({ name: 'desktop', w: 1200, h: 320 }),
  mobile: Object.freeze({ name: 'mobile', w: 390, h: 260 }),
});

// Layout tables. Every count in a cover derives from these constants and the
// viewport size, never from the request.
const LAYOUT = Object.freeze({
  arcs: {
    // tile x tile cells, two quarter arcs per cell
    desktop: { tile: 80, cols: 15, rows: 4, stroke: 16, accent: 3, dark: 0.35 },
    mobile: { tile: 65, cols: 6, rows: 4, stroke: 13, accent: 2, dark: 0.35 },
  },
  concentric: {
    // clusters of equally spaced rings, cluster centres on a fixed row
    desktop: { centers: [200, 600, 1000], cy: 160, rings: 7, step: 18, stroke: 6, sway: 12, accent: 2 },
    mobile: { centers: [195], cy: 130, rings: 7, step: 15, stroke: 5, sway: 0, accent: 1 },
  },
  bands: {
    // parallel diagonal bands, slope run/rise 0.6, clipped to the frame
    desktop: { pitch: 28, width: 16, slope: 0.6, phase: 6, accent: 2, dark: 0.4 },
    mobile: { pitch: 28, width: 16, slope: 0.6, phase: 6, accent: 2, dark: 0.4 },
  },
});

// ---------------------------------------------------------------------------
// Seeded randomness. The seed is the request hash and nothing else.

function seedWords(requestHash, family, viewport) {
  const digest = createHash('sha256').update(`${ADAPTER_ID}|${family}|${viewport}|${requestHash}`).digest();
  return [0, 4, 8, 12].map((offset) => digest.readUInt32BE(offset));
}

// sfc32: 32-bit integer arithmetic only, so it is identical on every platform.
function makeRng([a0, b0, c0, d0]) {
  let a = a0 >>> 0;
  let b = b0 >>> 0;
  let c = c0 >>> 0;
  let d = d0 >>> 0;
  const next = () => {
    const t0 = (a + b) | 0;
    a = b ^ (b >>> 9);
    b = (c + (c << 3)) | 0;
    c = (c << 21) | (c >>> 11);
    d = (d + 1) | 0;
    const t = (t0 + d) | 0;
    c = (c + t) | 0;
    return (t >>> 0) / 4294967296;
  };
  for (let i = 0; i < 16; i += 1) next();
  return next;
}

const int = (rng, n) => Math.floor(rng() * n);

function shuffled(rng, n) {
  const order = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i -= 1) {
    const j = int(rng, i + 1);
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

// Pick `count` cells of a cols x rows grid, at least `minDist` apart (Chebyshev),
// relaxing the distance only if the grid is too small. Always returns exactly
// `count` cells, so the accent count never depends on the seed.
function spacedPicks(rng, cols, rows, count, minDist) {
  const order = shuffled(rng, cols * rows);
  for (let dist = minDist; dist >= 0; dist -= 1) {
    const chosen = [];
    for (const index of order) {
      const c = index % cols;
      const r = Math.floor(index / cols);
      if (chosen.every(([pc, pr]) => Math.max(Math.abs(pc - c), Math.abs(pr - r)) >= dist)) chosen.push([c, r]);
      if (chosen.length === count) return chosen;
    }
  }
  return order.slice(0, count).map((index) => [index % cols, Math.floor(index / cols)]);
}

// One decimal, no "-0": identical bytes for identical numbers.
const f = (value) => String(Math.round(value * 10) / 10 + 0);
const pt = (x, y) => `${f(x)} ${f(y)}`;

// ---------------------------------------------------------------------------
// Families. Each returns an array of SVG element strings; `tone(name)` maps
// light, dark and accent to palette colours. Nothing here sees the request.

function drawArcs(vp, rng, tone) {
  const { tile, cols, rows, stroke, accent, dark } = LAYOUT.arcs[vp.name];
  const r = tile / 2;
  // Edge midpoints are the nodes; each quarter arc joins two of them, so a
  // connected run of arcs is one curve and keeps one grey from end to end.
  const horizontal = (c, row) => row * cols + c;
  const vertical = (c, row) => cols * (rows + 1) + c * rows + row;
  const parent = Array.from({ length: cols * (rows + 1) + (cols + 1) * rows }, (_, i) => i);
  const find = (i) => { let n = i; while (parent[n] !== n) { parent[n] = parent[parent[n]]; n = parent[n]; } return n; };
  const union = (a, b) => { parent[find(a)] = find(b); };
  const cells = [];
  for (let row = 0; row < rows; row += 1) {
    for (let c = 0; c < cols; c += 1) {
      const x = c * tile;
      const y = row * tile;
      const north = horizontal(c, row);
      const south = horizontal(c, row + 1);
      const west = vertical(c, row);
      const east = vertical(c + 1, row);
      const flip = rng() < 0.5;
      const arcs = flip
        ? [
          { nodes: [north, east], d: `M ${pt(x + tile - r, y)} A ${f(r)} ${f(r)} 0 0 0 ${pt(x + tile, y + r)}` },
          { nodes: [west, south], d: `M ${pt(x + r, y + tile)} A ${f(r)} ${f(r)} 0 0 0 ${pt(x, y + tile - r)}` },
        ]
        : [
          { nodes: [north, west], d: `M ${pt(x + r, y)} A ${f(r)} ${f(r)} 0 0 1 ${pt(x, y + r)}` },
          { nodes: [south, east], d: `M ${pt(x + tile - r, y + tile)} A ${f(r)} ${f(r)} 0 0 1 ${pt(x + tile, y + tile - r)}` },
        ];
      for (const arc of arcs) union(arc.nodes[0], arc.nodes[1]);
      cells.push({ c, row, arcs });
    }
  }
  const curveTone = new Map();
  for (const cell of cells) {
    for (const arc of cell.arcs) {
      const root = find(arc.nodes[0]);
      if (!curveTone.has(root)) curveTone.set(root, rng() < dark ? 'dark' : 'light');
      arc.tone = curveTone.get(root);
    }
  }
  for (const [c, row] of spacedPicks(rng, cols, rows, accent, 3)) cells[row * cols + c].arcs[int(rng, 2)].tone = 'accent';
  const out = [];
  for (const cell of cells) for (const arc of cell.arcs) out.push(`<path d="${arc.d}" stroke="${tone(arc.tone)}"/>`);
  return { elements: out, group: `fill="none" stroke-width="${stroke}" stroke-linecap="butt"` };
}

function drawConcentric(vp, rng, tone) {
  const { centers, cy, rings, step, stroke, sway, accent } = LAYOUT.concentric[vp.name];
  // The same fixed set of vertical offsets, dealt out to the clusters by seed.
  const offsets = [-sway, 0, sway];
  const dealt = shuffled(rng, centers.length).map((i) => offsets[i % offsets.length]);
  const clusterTone = centers.map(() => (rng() < 0.5 ? 'dark' : 'light'));
  const accentRings = new Map();
  for (const cluster of shuffled(rng, centers.length).slice(0, accent)) accentRings.set(cluster, int(rng, rings));
  const out = [];
  centers.forEach((cx, cluster) => {
    for (let k = 0; k < rings; k += 1) {
      const name = accentRings.get(cluster) === k ? 'accent' : clusterTone[cluster];
      out.push(`<circle cx="${f(cx)}" cy="${f(cy + dealt[cluster])}" r="${f((k + 1) * step)}" stroke="${tone(name)}"/>`);
    }
  });
  return { elements: out, group: `fill="none" stroke-width="${stroke}"` };
}

function clipHalfPlane(poly, axis, bound, keepAbove) {
  const inside = (p) => (keepAbove ? p[axis] >= bound : p[axis] <= bound);
  const out = [];
  for (let i = 0; i < poly.length; i += 1) {
    const a = poly[i];
    const b = poly[(i + 1) % poly.length];
    if (inside(a)) out.push(a);
    if (inside(a) !== inside(b)) {
      const t = (bound - a[axis]) / (b[axis] - a[axis]);
      out.push(axis === 0 ? [bound, a[1] + t * (b[1] - a[1])] : [a[0] + t * (b[0] - a[0]), bound]);
    }
  }
  return out;
}

function drawBands(vp, rng, tone) {
  const { pitch, width, slope, phase, accent, dark } = LAYOUT.bands[vp.name];
  const { w, h } = vp;
  const lean = slope * h;
  const count = Math.ceil((w + lean - phase) / pitch);
  const tones = [];
  for (let i = 0; i < count; i += 1) tones.push(rng() < dark ? 'dark' : 'light');
  for (const [i] of spacedPicks(rng, count, 1, accent, 4)) tones[i] = 'accent';
  const out = [];
  for (let k = 0; k < count; k += 1) {
    const x0 = -lean + phase + k * pitch;
    // a "/" leaning band: bottom edge at x0..x0+width, top edge shifted right by `lean`
    let poly = [[x0, h], [x0 + width, h], [x0 + width + lean, 0], [x0 + lean, 0]];
    poly = clipHalfPlane(poly, 0, 0, true);
    poly = clipHalfPlane(poly, 0, w, false);
    poly = clipHalfPlane(poly, 1, 0, true);
    poly = clipHalfPlane(poly, 1, h, false);
    const points = [];
    for (const [x, y] of poly) {
      const text = `${f(x)},${f(y)}`;
      if (points[points.length - 1] !== text) points.push(text);
    }
    out.push(`<polygon points="${points.join(' ')}" fill="${tone(tones[k])}"/>`);
  }
  return { elements: out, group: '' };
}

const DRAW = Object.freeze({ arcs: drawArcs, concentric: drawConcentric, bands: drawBands });

// The only entry the drawing code has: family, seed material and viewport.
function drawCover({ family, seed, viewport }, palette) {
  const vp = VIEWPORTS[viewport];
  const tones = { light: palette.series3, dark: palette.series5, accent: palette.accent };
  for (const [name, value] of Object.entries(tones)) if (!HEX_COLOR.test(String(value))) throw new Refusal(EXIT.PALETTE, `house palette colour '${name}' is missing or not a hex colour`);
  const tone = (name) => tones[name];
  const rng = makeRng(seedWords(seed, family, viewport));
  const { elements, group } = DRAW[family](vp, rng, tone);
  const accent = elements.filter((element) => element.includes(tones.accent)).length;
  const svg = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vp.w} ${vp.h}" role="img">`,
    `<g data-role="decorative-cover"${group ? ` ${group}` : ''}>`,
    ...elements,
    '</g>',
    '</svg>',
  ].join('\n');
  return { svg, counts: { elements: elements.length, accent } };
}

// ---------------------------------------------------------------------------
// Request handling.

class Refusal extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

function listSize(value) {
  if (value === undefined || value === null) return 0;
  return Array.isArray(value) ? value.length : 1;
}

function parseRequest(raw) {
  let request;
  try { request = JSON.parse(raw); } catch { throw new Refusal(EXIT.MALFORMED, 'request is not valid JSON'); }
  if (!request || typeof request !== 'object' || Array.isArray(request)) throw new Refusal(EXIT.MALFORMED, 'request must be a JSON object');
  if (request.protocol !== PROTOCOL) throw new Refusal(EXIT.MALFORMED, `request protocol must be ${PROTOCOL}`);
  if (typeof request.request_hash !== 'string' || !request.request_hash.trim()) throw new Refusal(EXIT.MALFORMED, 'request_hash is required');
  const spec = request.spec && typeof request.spec === 'object' ? request.spec : null;
  if (!spec) throw new Refusal(EXIT.MALFORMED, 'request spec is required');

  if (request.policy?.origin_policy !== 'software_only' || spec.origin_policy !== 'software_only') {
    throw new Refusal(EXIT.POLICY, 'geometric-cover only serves origin_policy=software_only');
  }
  if (listSize(spec.factual_elements) > 0 || listSize(request.evidence?.factual_elements) > 0) {
    throw new Refusal(EXIT.FACTUAL, 'geometric-cover is decorative: factual_elements must be empty');
  }
  if (DIGIT_OR_PERCENT.test(String(spec.title ?? '')) || DIGIT_OR_PERCENT.test(String(spec.alt ?? ''))) {
    throw new Refusal(EXIT.DIGITS, 'title and alt must not contain digits or percent signs');
  }
  const tokens = (Array.isArray(spec.constraints) ? spec.constraints : []).map(String).filter((constraint) => /motif\s*=/i.test(constraint));
  if (tokens.length !== 1) throw new Refusal(EXIT.MOTIF, `constraints must carry exactly one motif=<family> token (${FAMILIES.join(', ')})`);
  const match = /^motif=([a-z]+)$/.exec(tokens[0].trim());
  if (!match || !FAMILIES.includes(match[1])) throw new Refusal(EXIT.MOTIF, `motif must be one of ${FAMILIES.join(', ')}`);
  return { family: match[1], seed: request.request_hash };
}

async function loadHousePalette() {
  const candidates = [new URL('../viz.mjs', import.meta.url), new URL('./viz.mjs', import.meta.url)].filter((url) => existsSync(fileURLToPath(url)));
  if (!candidates.length) throw new Refusal(EXIT.PALETTE, 'viz.mjs not found beside the adapter');
  const palette = (await import(candidates[0].href)).HOUSE_PALETTES?.house;
  if (!palette) throw new Refusal(EXIT.PALETTE, 'viz.mjs has no house palette');
  return palette;
}

function buildResponse({ family, seed }, palette) {
  const desktop = drawCover({ family, seed, viewport: 'desktop' }, palette);
  const mobile = drawCover({ family, seed, viewport: 'mobile' }, palette);
  return {
    adapter_id: ADAPTER_ID,
    origin: 'software',
    digital_source_type: 'algorithmicMedia',
    version: '1',
    disclosure: DISCLOSURE,
    license: LICENSE,
    variants: { desktop: desktop.svg, mobile: mobile.svg },
    metadata: { decorative: true, motif: family, element_counts: { desktop: desktop.counts.elements, mobile: mobile.counts.elements } },
  };
}

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString('utf8');
}

async function main() {
  try {
    const choice = parseRequest(await readStdin());
    const palette = await loadHousePalette();
    process.stdout.write(`${JSON.stringify(buildResponse(choice, palette))}\n`);
  } catch (error) {
    const known = error instanceof Refusal;
    process.stderr.write(`geometric-cover: ${known ? '' : 'internal error: '}${String(error?.message ?? error).split('\n')[0]}\n`);
    process.exitCode = known ? error.code : EXIT.INTERNAL;
  }
}

await main();
